def calculate_nutrition(ingredients: list) -> dict:
    """Расчёт КБЖУ для всего блюда."""
    total = {"ккал": 0, "белки": 0, "жиры": 0, "углеводы": 0}
    for ing in ingredients:
        if ing.get("by_taste") or ing.get("quantity") is None:
            continue
        name = ing.get("name", "").lower()
        qty = ing.get("quantity", 0) or 0
        unit = ing.get("unit", "")

        # Перевод в граммы
        if unit == "банка":
            grams = can_to_grams(name, qty)
        elif unit == "мл":
            grams = qty
        elif unit == "шт":
            grams = qty * 50
        elif unit == "ст.л":
            grams = qty * 15
        elif unit == "ч.л":
            grams = qty * 5
        elif unit == "кг":
            grams = qty * 1000
        else:
            grams = qty

        # Ищем в базе напрямую, потом по вхождению
        entry = NUTRITION_DB.get(name)
        if not entry:
            for key in NUTRITION_DB:
                if key in name or name in key:
                    entry = NUTRITION_DB[key]
                    break

        if entry:
            kcal, prot, fat, carb = entry
            factor = grams / 100
            total["ккал"] += kcal * factor
            total["белки"] += prot * factor
            total["жиры"] += fat * factor
            total["углеводы"] += carb * factor

    return {k: round(v, 1) for k, v in total.items()}
